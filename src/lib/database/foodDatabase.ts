/**
 * Searches the verified food database by exact or fuzzy keyword matches.
 */
export function searchFoodDatabase(query: string): VerifiedFoodItem[] {
  if (!query || query.trim() === "") return VERIFIED_FOOD_DATABASE.slice(0, 10);
  const clean = query.trim().toLowerCase();

  return VERIFIED_FOOD_DATABASE.filter((item) => {
    if (item.name.toLowerCase().includes(clean)) return true;
    if (item.category.toLowerCase().includes(clean)) return true;
    return item.aliases.some((alias) => alias.toLowerCase().includes(clean));
  }).sort((a, b) => {
    // Exact or starting match priority
    const aStartsWith = a.name.toLowerCase().startsWith(clean);
    const bStartsWith = b.name.toLowerCase().startsWith(clean);
    if (aStartsWith && !bStartsWith) return -1;
    if (!aStartsWith && bStartsWith) return 1;
    return 0;
  });
}

/**
 * Looks up the closest matching verified food item given an AI detected label.
 */
export function findMatchingVerifiedFood(rawName: string): VerifiedFoodItem | null {
  if (!rawName) return null;
  const clean = rawName.trim().toLowerCase();

  // 1. Direct match by ID
  const byId = VERIFIED_FOOD_DATABASE.find((f) => f.id === clean);
  if (byId) return byId;

  // 2. Direct name match
  const byName = VERIFIED_FOOD_DATABASE.find(
    (f) => f.name.toLowerCase() === clean || clean.includes(f.name.toLowerCase())
  );
  if (byName) return byName;

  // 3. Alias match
  const byAlias = VERIFIED_FOOD_DATABASE.find((f) =>
    f.aliases.some((alias) => clean === alias || clean.includes(alias) || alias.includes(clean))
  );
  if (byAlias) return byAlias;

  return null;
}

/**
 * Calculates exact nutrition for a given weight in grams using verified 100g base.
 */
export function calculateNutritionFromGrams(item: VerifiedFoodItem, grams: number) {
  const factor = grams / 100;
  return {
    calories: Math.round(item.caloriesPer100g * factor),
    protein: Math.round(item.proteinPer100g * factor * 10) / 10,
    carbs: Math.round(item.carbsPer100g * factor * 10) / 10,
    fat: Math.round(item.fatPer100g * factor * 10) / 10,
    fiber: item.fiberPer100g ? Math.round(item.fiberPer100g * factor * 10) / 10 : undefined,
  };
}
