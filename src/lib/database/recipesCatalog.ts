/**
 * Searches curated recipes by free text or tag.
 */
export function searchRecipes(query: string): Recipe[] {
  if (!query || query.trim() === "") return CURATED_RECIPES;
  const clean = query.trim().toLowerCase();

  return CURATED_RECIPES.filter((r) => {
    return (
      r.name.toLowerCase().includes(clean) ||
      r.description.toLowerCase().includes(clean) ||
      r.cuisine.toLowerCase().includes(clean) ||
      r.dietaryTags.some((t) => t.toLowerCase().includes(clean)) ||
      r.ingredients.some((i) => i.name.toLowerCase().includes(clean))
    );
  });
}
